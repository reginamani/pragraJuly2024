package aug20.aggregation;

public class AddressEmp {
    String street;
    String city;
    String country;
    String postalCode;

    public AddressEmp(String street, String city, String country, String postalCode) {
        this.street = street;
        this.city = city;
        this.country = country;
        this.postalCode = postalCode;
    }
}
